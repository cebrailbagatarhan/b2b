export type Dictionary = (typeof dictionaries)[Locale]

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale] ?? dictionaries.tr
}

/** Maps DB category names (Turkish) to the active UI language. */
export function translateCategoryName(name: string, locale: Locale): string {
  const dict = getDictionary(locale)
  const mapped = dict.categoryNames[name as keyof typeof dict.categoryNames]
  return mapped ?? name
}

export function formatProductCount(count: number, locale: Locale): string {
  return getDictionary(locale).productCount.replace('{n}', String(count))
}

export function formatMoney(
  amount: number,
  currency: string,
  locale: Locale
): string {
  return new Intl.NumberFormat(locale === 'en' ? 'en-US' : 'tr-TR', {
    style: 'currency',
    currency: currency || 'TRY',
  }).format(amount)
}
